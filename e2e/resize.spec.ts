import { expect, test } from '@playwright/test'

test('E3: SplitPane divider responds to arrow/Home/End keyboard', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 800 })
  await page.goto('/')
  const divider = page.locator('[aria-label="Resize board and log split"]')
  await expect(divider).toHaveAttribute('tabindex', '0')
  const before = Number(await divider.getAttribute('aria-valuenow'))
  await divider.focus()
  await page.keyboard.press('ArrowRight')
  const afterRight = Number(await divider.getAttribute('aria-valuenow'))
  expect(afterRight).not.toBe(before)
  await page.keyboard.press('Home')
  const afterHome = Number(await divider.getAttribute('aria-valuenow'))
  await page.keyboard.press('End')
  const afterEnd = Number(await divider.getAttribute('aria-valuenow'))
  expect(afterEnd).toBeGreaterThan(afterHome)
})

test('E3: Board edge handles are focusable and resize via keyboard', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 800 })
  await page.goto('/')
  const right = page.locator('[aria-label="Resize board right edge"]')
  await expect(right).toHaveAttribute('tabindex', '0')
  await expect(right).toHaveAttribute('aria-valuemin', '440')
  await expect(right).toHaveAttribute('aria-valuemax', '1360')
  const before = Number(await right.getAttribute('aria-valuenow'))
  await right.focus()
  await page.keyboard.press('ArrowRight')
  const after = Number(await right.getAttribute('aria-valuenow'))
  expect(after).toBe(before + 16)

  const bottom = page.locator('[aria-label="Resize board bottom edge"]')
  await expect(bottom).toHaveAttribute('tabindex', '0')
  const hBefore = Number(await bottom.getAttribute('aria-valuenow'))
  await bottom.focus()
  await page.keyboard.press('ArrowDown')
  const hAfter = Number(await bottom.getAttribute('aria-valuenow'))
  expect(hAfter).toBe(hBefore + 16)
})